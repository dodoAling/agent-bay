import assert from 'node:assert/strict';
import { stat } from 'node:fs/promises';
import { join, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { assertRuntimeVersion, command, filesUnder, GENERATOR, json, managedPath, PROJECT_ROOT, sha256 } from './desktop-assets.mjs';

export async function checkDesktopAssets() {
  const server = await managedPath(PROJECT_ROOT, 'src-tauri/resources/server');
  const manifest = await json(join(server, 'asset-manifest.json'));
  assert.equal(manifest.generator, GENERATOR, 'Desktop resources must be generated by desktop-prepare.mjs.');
  assertRuntimeVersion(manifest.runtime.version);
  const binary = await managedPath(PROJECT_ROOT, manifest.runtime.path);
  assert.equal(await sha256(binary), manifest.runtime.sha256, 'The bundled Node.js runtime changed.');
  assert.equal((await stat(binary)).size, manifest.runtime.size, 'The bundled Node.js runtime size changed.');
  assert.equal(await sha256(join(PROJECT_ROOT, 'package.json')), manifest.package.sourceSha256, 'package.json changed; prepare desktop resources again.');
  assert.equal(await sha256(join(PROJECT_ROOT, 'package-lock.json')), manifest.package.lockSha256, 'package-lock.json changed; prepare desktop resources again.');
  for (const source of manifest.sourceInputs) {
    const path = await managedPath(PROJECT_ROOT, source.path);
    assert.equal(await sha256(path), source.sha256, `Source changed; prepare desktop resources again: ${source.path}`);
  }
  const actualFiles = (await filesUnder(server)).map(file => file.name).filter(name => name !== 'asset-manifest.json').sort();
  assert.deepEqual(actualFiles, manifest.assets.map(file => file.path).sort(), 'The staged asset inventory changed.');
  for (const asset of manifest.assets) {
    const path = await managedPath(PROJECT_ROOT, `src-tauri/resources/server/${asset.path}`);
    assert.equal(await sha256(path), asset.sha256, `Staged asset changed: ${asset.path}`);
    assert.equal((await stat(path)).size, asset.size, `Staged asset size changed: ${asset.path}`);
  }
  for (const required of ['bootstrap.mjs', 'src/server.mjs', 'public/index.html', 'public/app.js', 'licenses/NODE-LICENSE.txt', 'node_modules/@modelcontextprotocol/client/package.json', 'scripts/emit.mjs', 'scripts/mcp-proxy.mjs', 'examples/agent-events.mjs', 'examples/agent_events.py']) {
    assert.ok(actualFiles.includes(required), `Required desktop resource: ${required}`);
  }
  assert.ok(!actualFiles.some(path => path.includes('node_modules/playwright') || path.includes('node_modules/@tauri-apps/')), 'Development dependencies must not be bundled with the server.');
  const version = await command(binary, ['--version']);
  assert.equal(version, `v${manifest.runtime.version}`, 'The sidecar version must match its manifest.');
  await command(binary, ['--check', join(server, 'bootstrap.mjs')]);
  for (const script of ['scripts/emit.mjs', 'scripts/mcp-proxy.mjs', 'examples/agent-events.mjs']) await command(binary, ['--check', join(server, script)]);
  const entry = pathToFileURL(join(server, 'src/server.mjs')).href;
  const packagedRoot = pathToFileURL(server + sep).href;
  const importCheck = `import { registerHooks } from 'node:module';
    registerHooks({ resolve(specifier, context, nextResolve) {
      const result = nextResolve(specifier, context);
      if (result.url.startsWith('file:') && !result.url.startsWith(${JSON.stringify(packagedRoot)})) throw new Error('Production import escaped packaged resources: ' + result.url);
      return result;
    } });
    const app = await import(${JSON.stringify(entry)});
    if (typeof app.createApp !== 'function') throw new Error('Missing createApp export');
    console.log('production-import-ok');`;
  const output = await command(binary, ['--input-type=module', '-e', importCheck], { cwd: server });
  assert.equal(output, 'production-import-ok', 'The staged server must import using only production dependencies.');
  return { passed: true, target: manifest.target, runtimeVersion: manifest.runtime.version, productionPackages: manifest.dependencies.length,
    verifiedAssets: manifest.assets.length, sourceInputs: manifest.sourceInputs.length, stagedImport: true, targetExecuted: false, serverStarted: false };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  checkDesktopAssets().then(result => console.log(JSON.stringify(result, null, 2))).catch(error => { console.error(`Desktop asset check failed: ${error.message}`); process.exitCode = 1; });
}
